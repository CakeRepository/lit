    def test_enum_member_extents_leave_the_comma_in_the_gap(self):
        source = b"enum E\n{\n    A,\n    B,\n    C\n}\n"
        (enum,) = tree(source)
        self.assertEqual([n[0] for n in enum[3]], ["member A", "member B", "member C"])
        self.assertEqual([source[n[1]:n[2]] for n in enum[3]], [b"    A", b"    B", b"    C\n"])

    def test_extents_follow_the_contract(self):
        source = b"using A; using B;\n  public class C { int x; }  // c\n"
        a, b, c = tree(source)
        self.assertEqual(source[a[1]:a[2]], b"using A;")
        self.assertEqual(source[b[1]:b[2]], b"using B;\n")
        self.assertEqual(source[c[1]:c[2]], b"  public class C { int x; }")
        self.assertEqual(source[c[3][0][1]:c[3][0][2]], b"int x;")

    def test_comments_regions_and_pragmas_stay_in_the_gap(self):
        source = b"#pragma warning disable CS1591\n#region Core\n/// <summary>doc</summary>\n[Obsolete]\npublic class C { }\n#endregion\n"
        (c,) = tree(source)
        self.assertEqual(source[c[1]:c[2]], b"[Obsolete]\npublic class C { }\n")

    def test_bom_stays_in_the_gap_and_offsets_are_bytes(self):
        source = "\ufeffusing System;\nclass \u00c9t\u00e9 { string s = \"\u00e9\u20ac\U0001f600\"; int x; }\n".encode("utf-8")
        using, cls = tree(source)
        self.assertEqual(using[1], 3)
        self.assertEqual(source[cls[1]:cls[2]].decode("utf-8"), "class \u00c9t\u00e9 { string s = \"\u00e9\u20ac\U0001f600\"; int x; }\n")
        self.assertEqual(source[cls[3][1][1]:cls[3][1][2]], b"int x;")

