    def test_a_large_file_is_fast(self):
        method = (
            b"        /// <summary>Method %d.</summary>\n        [Obsolete(\"x\")]\n"
            b"        public int Method%d(int a, string b)\n        {\n            var s = $\"{a} {b:N2} {{x}}\";\n"
            b"            if (a > %d) { return a; }\n            return s.Length;\n        }\n\n"
        )
        body = b"".join(method % (n, n, n) for n in range(600))
        source = b"using System;\n\nnamespace Big\n{\n    public class C\n    {\n" + body + b"    }\n}\n"
        self.assertGreater(source.count(b"\n"), 4500)
        started = time.perf_counter()
        nodes = csharp.outline(source, ".cs")
        self.assertLess(time.perf_counter() - started, 1.0)
        self.assertEqual(len(nodes[1][3][0][3]), 600)

    def test_non_utf8_and_nul_are_refused(self):
        self.assertIsNone(csharp.outline(b"class A { string s = \"\xe9\"; }\n", ".cs"))
        self.assertIsNone(csharp.outline(b"class A { }\x00\n", ".cs"))


