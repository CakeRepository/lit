    def test_declaration_forms(self):
        source = (
            b"global using System;\nextern alias Lib;\n[assembly: Foo(\"x\")]\n"
            b"public abstract class A<T> : B<T> where T : class, new()\n{\n"
            b"    public abstract T Make();\n    protected internal virtual int P { get; private set; }\n"
            b"    public int Q { get; } = Compute(1, 2);\n    public required string R { get; init; }\n"
            b"    public int[] Arr = { 1, 2 }, Other = new int[3];\n    public Dictionary<int, string> D = new Dictionary<int, string>(), E;\n"
            b"    public (int, int) Pair() => (1, 2);\n    public static bool operator ==(A<T> a, A<T> b) => true;\n"
            b"    public static A<T> operator <<(A<T> a, int b) => a;\n    event EventHandler Multi1, Multi2;\n"
            b"    event EventHandler Custom { add { } remove { } }\n    int IFoo.Explicit => 1;\n"
            b"    int IList<int>.this[int i] => i;\n    void IFoo<int>.Run() { }\n"
            b"    public struct S;\n}\n"
        )
        self.assertIsNone(keys(source))  # `struct S;` is not valid C#
